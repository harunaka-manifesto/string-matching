// Rebuilds the legacy sheet order (tab → variable names by row) that the Figma
// collections lost during migration. The plugin uses it to prefill strings in
// reading order, and shows each string's legacy screen. Legacy order is historical, so this only changes if the
// registry is re-migrated.
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { gzipSync } from 'node:zlib';
import { prepareRegistry } from './prepare-copy-library.mjs';

const root = resolve(new URL('..', import.meta.url).pathname);
const registry = resolve(root, 'figma-copy-migration/registry/copy-registry.jsonl');
const output = resolve(root, 'apps/plugin/src/generated/order-index.ts');

const rows = new Map();
const source = (await readFile(registry, 'utf8'))
  .split('\n')
  .filter((line) => line.trim())
  .map((line) => JSON.parse(line));
const prepared = prepareRegistry(source).rows;
const byId = new Map(prepared.map((entity) => [entity.copyId, entity]));
const metadata = {};
const catalog = {};
const location = (entity) =>
  [entity.metadata?.section, entity.feature, entity.screen, entity.context]
    .filter((part) => part && !['general', 'shared', 'main'].includes(part))
    .join(' › ');
for (const entity of source) {
  let canonical = byId.get(entity.copyId);
  const seen = new Set();
  while (canonical?.metadata?.mergedInto && !seen.has(canonical.copyId)) {
    seen.add(canonical.copyId);
    canonical = byId.get(canonical.metadata.mergedInto);
  }
  if (!canonical || canonical.status !== 'active' || canonical.metadata?.importHeld) continue;
  metadata[entity.name] = [entity.copyId, canonical.name, entity.role];
  metadata[canonical.name] = [canonical.copyId, canonical.name, canonical.role];
  catalog[canonical.name] ??= {
    aliases: [
      ...new Set([
        ...(canonical.legacyKeys ?? []),
        ...(canonical.metadata.usages ?? []).map((usage) => usage.name),
      ]),
    ],
    contexts: (
      canonical.metadata.usages ?? [
        { product: canonical.domain, path: location(canonical), role: canonical.role },
      ]
    ).map((usage) => ({
      product: usage.product,
      path:
        usage.path ??
        [usage.section, usage.feature, usage.screen, usage.context].filter(Boolean).join(' › '),
      role: usage.role,
    })),
  };
}
// Readable screen path per variable (legacy section › screen), shown to tell identical values apart.
const sections = [];
const sectionIndex = new Map();
const paths = {};
// Split on \n only: some copy values contain bare \r characters.
for (const entity of source) {
  if (!entity.name) continue;
  const section = (entity.metadata?.section ?? '').trim();
  const screen = entity.screen && entity.screen !== 'shared' ? entity.screen : '';
  if (section || screen) {
    if (!sectionIndex.has(section)) {
      sectionIndex.set(section, sections.length);
      sections.push(section);
    }
    const context = entity.context && entity.context !== 'main' ? entity.context : '';
    paths[entity.name] = [sectionIndex.get(section), screen, context, entity.role ?? ''];
  }
  for (const source of entity.legacySources ?? []) {
    if (!source.tab || typeof source.rec !== 'number') continue;
    const list = rows.get(source.tab) ?? [];
    list.push({ rec: source.rec, part: source.part ?? '', name: entity.name });
    rows.set(source.tab, list);
  }
}

const tabs = {};
for (const tab of [...rows.keys()].sort()) {
  const list = rows.get(tab).sort((a, b) => a.rec - b.rec || a.part.localeCompare(b.part));
  const names = [];
  for (const item of list) if (names.at(-1) !== item.name) names.push(item.name);
  tabs[tab] = names;
}

await mkdir(dirname(output), { recursive: true });
// Shipped gzipped + base64 to keep ui.html small; the UI inflates it with DecompressionStream.
const packed = gzipSync(JSON.stringify({ tabs, sections, paths, metadata, catalog }), {
  level: 9,
}).toString('base64');
await writeFile(
  output,
  '// Generated by scripts/build-order-index.mjs from copy-registry.jsonl. Do not edit.\n' +
    `export const ORDER_INDEX_GZIP_BASE64 =\n  '${packed}';\n`,
);
const total = Object.values(tabs).reduce((sum, names) => sum + names.length, 0);
console.log(
  `Order index: ${Object.keys(tabs).length} tabs, ${total} positions, ${Object.keys(paths).length} paths → ${output}`,
);
